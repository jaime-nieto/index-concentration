"""
Save tables as CSV (full precision) and Markdown (formatted), and collect all
Markdown tables into results/summary.md. Every number quoted in the README
comes from that file.
"""
from datetime import datetime, timezone
import json

from . import config

_SECTIONS = []

LABELS = {"index": "Index weights", "equal": "Equal weight", "fixed": "Today's weights, held fixed"}


def pct(x, digits=1):
    return f"{100 * x:.{digits}f}%"


def points(x, digits=1):
    """A difference between two percentages."""
    return f"{100 * x:+.{digits}f}"


def num(x, digits=2):
    return f"{x:.{digits}f}"


def interval(d, digits=1, scale=100):
    return f"{scale * d['difference']:+.{digits}f} ({scale * d['low']:+.{digits}f} to {scale * d['high']:+.{digits}f})"


def to_markdown(df):
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in row.values) + " |")
    return "\n".join(lines)


def save_table(name, title, pretty, raw=None, note=""):
    """Write <name>.csv (raw numbers) and <name>.md (formatted) and register it."""
    config.TABLE_DIR.mkdir(parents=True, exist_ok=True)
    (raw if raw is not None else pretty).to_csv(config.TABLE_DIR / f"{name}.csv", index=False)
    md = f"### {title}\n\n{to_markdown(pretty)}\n"
    if note:
        md += f"\n{note}\n"
    (config.TABLE_DIR / f"{name}.md").write_text(md, encoding="utf-8")
    _SECTIONS.append(md)


def write_summary():
    manifest_file = config.RAW_DIR / "manifest.json"
    manifest = json.loads(manifest_file.read_text()) if manifest_file.exists() else {}
    downloaded = sorted({v["downloaded_at_utc"] for v in manifest.values()}) if manifest else ["-"]
    months = ", ".join(str(m) for m in config.REBALANCE_MONTHS)
    header = (
        "# Results summary (generated by `run_all.py` — do not edit by hand)\n\n"
        f"- Generated: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC\n"
        f"- Indices: {', '.join(config.INDICES[k]['name'] for k in config.ORDER)}, "
        f"with the members and weights of {config.AS_OF} only\n"
        f"- Period: {config.SAMPLE_START} to {config.AS_OF}\n"
        f"- Data downloaded (UTC): {downloaded[0]} to {downloaded[-1]}\n"
        f"- Equal weight is rebalanced on the last trading day of months {months}; "
        f"costs {config.COST_BPS:g} bp per unit traded\n"
        "- Returns include dividends and are in the currency of each index\n\n"
    )
    text = header + "\n".join(_SECTIONS)
    (config.ROOT / "results" / "summary.md").write_text(text, encoding="utf-8")
